static void send_request(struct dhcp_context* ctx) {
    struct dhcp_packet request = {};

    request.op = BOOTREQUEST;
    request.htype = 1;
    request.hlen = 6;
    request.xid = htonl(ctx->xid);
    request.flags = htons(0x8000);
    request.magic = htonl(MAGIC_COOKIE);

    memcpy(request.chaddr, ctx->mac, 6);

    uint8_t* opt = request.options;

    *opt++ = DHCP_OPTION_MESSAGE_TYPE;
    *opt++ = 1;
    *opt++ = DHCP_REQUEST;

    *opt++ = DHCP_OPTION_REQUESTED_IP;
    *opt++ = 4;
    memcpy(opt, &ctx->offer.ip, 4);
    opt += 4;

    *opt++ = DHCP_OPTION_SERVER_ID;
    *opt++ = 4;
    memcpy(opt, &ctx->offer.server_id, 4);
    opt += 4;

    *opt++ = DHCP_OPTION_END;

    size_t len  = sizeof(request) - sizeof(request.options) + (opt - request.options);

    struct sockaddr_in dest = {
        .sin_family = AF_INET,
        .sin_port = htons(67),
        .sin_addr.s_addr = INADDR_BROADCAST,
    };

    if (sendto(ctx->sockfd, &request, len, 0, (struct sockaddr*) &dest, sizeof(dest)) < 0) {
        err(EXIT_FAILURE, "sendto");
    }
}

static void usage(void) {
    fprintf(stderr, "usage: dhcpd [-c CONFIG]\n");
    exit(EXIT_FAILURE);
}

int main(int argc, char* argv[]) {
    const char* config_path = _PATH_CONFIG;

    int c;
    while ((c = getopt(argc, argv, "c:")) != -1) {
        switch (c) {
            case 'c':
                config_path = optarg;
                break;
            default:
                usage();
        }
    }

    argc -= optind;
    argv += optind;

    if (argc > 0) {
        warnx("extra operands provided");
        usage();
    }

    srand(time(NULL) ^ getpid());

    config = config_load_from_file(config_path);
    if (!config) {
        errx(EXIT_FAILURE, "failed to load config");
    }

    size_t capacity = 2;
    size_t interface_count = 0;

    struct dhcp_context* contexts = malloc(sizeof(struct dhcp_context) * capacity);
    if (!contexts) {
        errx(EXIT_FAILURE, "malloc");
    }

    config_iterator_t iter;
    config_iterator_init(&iter, &config->root, "interface");

    config_node_t* interface;
    while ((interface = config_iterator_next(&iter))) {
        const char* interface_name;
        if (config_value_get_string(interface, 0, &interface_name) < 0) {
            warnx("config: missing interface name");
            continue;
        }

        if (interface_count == capacity) {
            capacity *= 2;
            contexts = reallocarray(contexts, capacity, sizeof(struct dhcp_context));
            if (!contexts) {
                err(EXIT_FAILURE, "reallocarray");
            }
        }

        struct dhcp_context* ctx = &contexts[interface_count++];
        memset(ctx, 0, sizeof(struct dhcp_context));

        strncpy(ctx->interface_name, interface_name, sizeof(ctx->interface_name));
        ctx->interface_name[IFNAMSIZ - 1] = '\0';

        config_node_t* request = config_find(interface, "request");
        if (request && config_value_count(request)) {
            for (size_t i = 0; i < config_value_count(request); i++) {
                const char* value;
                if (config_value_get_string(request, i, &value) < 0) {
                    continue;
                }

                if (strcmp(value, "dns") == 0) {
                    ctx->request_options |= REQUEST_DNS;
                } else if (strcmp(value, "mtu") == 0) {
                    ctx->request_options |= REQUEST_INTERFACE_MTU;
                } else if (strcmp(value, "routers") == 0) {
                    ctx->request_options |= REQUEST_ROUTER;
                } else if (strcmp(value, "subnet-mask") == 0) {
                    ctx->request_options |= REQUEST_SUBNET_MASK;
                }
            }
        }

        config_node_t* retries = config_find(interface, "retry");

        long value;
        if (config_value_get_int(retries, 0, &value) < 0) {
            warnx("config: failed to parse retry value");
        }

        if (value <= 0) {
            warnx("config: invalid retry value: %ld", value);
        }

        ctx->max_retries = (size_t) value;

        ctx->sockfd = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);
        if (ctx->sockfd < 0) {
            err(EXIT_FAILURE, "socket");
        }

        struct ifreq ifr = {};
        strcpy(ifr.ifr_name, ctx->interface_name);

        if (ioctl(ctx->sockfd, SIOCIFBIND, &ifr) < 0) {
            err(EXIT_FAILURE, "ioctl(SIOCIFBIND)");
        }

        if (ioctl(ctx->sockfd, SIOCGIFHWADDR, &ifr) < 0) {
            err(EXIT_FAILURE, "ioctl(SIOCGIFHWADDR)");
        }

        memcpy(ctx->mac, (uint8_t*) ifr.ifr_hwaddr.sa_data, 6);

        struct sockaddr_in local = {
            .sin_family = AF_INET,
            .sin_port = htons(68),
            .sin_addr.s_addr = INADDR_ANY,
        };

        if (bind(ctx->sockfd, (struct sockaddr*) &local, sizeof(local)) < 0) {
            err(EXIT_FAILURE, "bind");
        }

        ctx->xid = rand();
        ctx->state = STATE_SELECTING;
    }

    config_free(config);

    struct pollfd* fds = malloc(sizeof(struct pollfd) * interface_count);
    if (!fds) {
        errx(EXIT_FAILURE, "malloc");
    }

    for (size_t i = 0; i < interface_count; i++) {
        struct dhcp_context* ctx = &contexts[i];

        printf("%s discover\n", ctx->interface_name);
        send_discover(ctx);

        struct timespec now;
        if (clock_gettime(CLOCK_MONOTONIC, &now) < 0) {
            err(EXIT_FAILURE, "clock_gettime(CLOCK_MONOTONIC)");
        }

        ctx->deadline = now;
        ctx->deadline.tv_sec += 1;
    }

    for (;;) {
        build_pollfds(contexts, fds, interface_count);

        struct timespec timeout = calculate_timeout(contexts, interface_count);

        int ret = ppoll(fds, interface_count, &timeout, NULL);
        if (ret < 0) {
            if (errno == EINTR) {
                continue;
            }

            err(EXIT_FAILURE, "ppoll");
        }

        for (size_t i = 0; i < interface_count; i++) {
            if (!(fds[i].revents & POLLIN)) {
                continue;
            }

            receive(&contexts[i]);
        }

        process_timers(contexts, interface_count);
    }

    free(fds);
    free(contexts);

    return EXIT_SUCCESS;
}
