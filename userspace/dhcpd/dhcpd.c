#define BOOTREQUEST 1
#define BOOTREPLY   2

#define DHCP_DISCOVER   1
#define DHCP_OFFER      2
#define DHCP_REQUEST    3
#define DHCP_ACK        5
#define DHCP_NAK        6

#define DHCP_OPTION_SUBNET_MASK     1
#define DHCP_OPTION_ROUTER          3
#define DHCP_OPTION_DNS             6
#define DHCP_OPTION_INTERFACE_MTU   26
#define DHCP_OPTION_REQUESTED_IP    50
#define DHCP_OPTION_IP_LEASE_TIME   51
#define DHCP_OPTION_MESSAGE_TYPE    53
#define DHCP_OPTION_SERVER_ID       54
#define DHCP_OPTION_PARAM_LIST      55
#define DHCP_OPTION_RENEWAL_TIME    58
#define DHCP_OPTION_REBIND_TIME     59
#define DHCP_OPTION_END             255

#define MAGIC_COOKIE 0x63825363

#define REQUEST_DNS             (1 << 0)
#define REQUEST_INTERFACE_MTU   (1 << 1)
#define REQUEST_ROUTER          (1 << 2)
#define REQUEST_SUBNET_MASK     (1 << 3)

#define _PATH_CONFIG "/etc/dhcpd.conf"

struct dhcp_packet {
    uint8_t op;
    uint8_t htype;
    uint8_t hlen;
    uint8_t hops;

    uint32_t xid;

    uint16_t secs;
    uint16_t flags;

    uint32_t ciaddr;
    uint32_t yiaddr;
    uint32_t siaddr;
    uint32_t giaddr;

    uint8_t chaddr[16];
    uint8_t sname[64];
    uint8_t file[128];

    uint32_t magic;

    uint8_t options[312];
} __attribute__((packed));

struct dhcp_lease {
    uint32_t ip;
    uint32_t mask;
    uint32_t gateway;
    uint32_t server_id;

    uint32_t lease_seconds;
    uint32_t renewal_seconds;
    uint32_t rebind_seconds;

    uint32_t* dns;
    size_t dns_count;

    struct timespec acquired;
};

enum dhcp_state {
    STATE_SELECTING,
    STATE_REQUESTING,
    STATE_BOUND,
    STATE_RENEWING,
    STATE_REBINDING,
    STATE_FAILED,
};

struct dhcp_context {
    char interface_name[IFNAMSIZ];
    int request_options;

    size_t retries;
    size_t max_retries;

    int sockfd;
    enum dhcp_state state;

    uint8_t mac[6];
    uint32_t xid;

    struct dhcp_lease lease;
    struct dhcp_lease offer;

    struct timespec deadline;

    struct timespec renewal_deadline;
    struct timespec rebind_deadline;
    struct timespec expiry_deadline;
};

static config_t* config;

static inline struct timespec timespec_add_seconds(struct timespec ts, uint32_t seconds) {
    ts.tv_sec += seconds;
    return ts;
}

static inline bool timespec_expired(struct timespec now, struct timespec deadline) {
    return now.tv_sec > deadline.tv_sec || (now.tv_sec == deadline.tv_sec && now.tv_nsec >= deadline.tv_nsec);
}

static inline struct timespec timespec_sub(struct timespec a, struct timespec b) {
    struct timespec result = {
        .tv_sec = a.tv_sec - b.tv_sec,
        .tv_nsec = a.tv_nsec - b.tv_nsec,
    };

    if (result.tv_nsec < 0) {
        result.tv_sec--;
        result.tv_nsec += 1000000000L;
    }

    if (result.tv_sec < 0) {
        return (struct timespec) {};
    }

    return result;
}

